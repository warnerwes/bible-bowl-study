const fs = await import("node:fs");
const fsp = await import("node:fs/promises");
const path = await import("node:path");
const { fileURLToPath } = await import("node:url");

const helpers = await import("./lib/inventory-helpers.mjs");

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..", "..", "..");
const DOCS_DIR = path.join(ROOT, "generator", "docs");
const JSON_PATH = path.join(DOCS_DIR, "exodus-factory-inventory.json");
const MD_PATH = path.join(DOCS_DIR, "exodus-factory-inventory.md");
const TARGET = helpers.TARGET_SCRIPTS;

function ensureDir(dir) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

function readScriptLines(relPath) {
  return fs.readFileSync(path.join(ROOT, relPath), "utf8").split(/\r?\n/);
}

function buildInventory() {
  const scripts = [];
  for (const relPath of TARGET) {
    scripts.push({
      path: relPath,
      summary: helpers.SUMMARIES[relPath],
      findings: helpers.analyzeScript(relPath, readScriptLines(relPath)),
    });
  }
  return {
    generatedAt: new Date().toISOString(),
    generator: "generator/toolchain/scripts/inventory-exodus-factory.mjs",
    scripts,
  };
}

function buildMarkdown(inventory) {
  const out = [
    "# Exodus Factory Inventory",
    "",
    `Generated by \`${inventory.generator}\` at ${inventory.generatedAt}.`,
    "",
    "This inventory maps each existing Exodus factory script to its behaviors, tagging findings as **book-specific** (Exodus literals, hardcoded paths, group placeholders, source-text hooks) or **book-agnostic** (reusable schema, merge, review, CSV, audit/verify logic).",
    "",
  ];
  for (const script of inventory.scripts) {
    out.push(`## ${script.path}`);
    out.push("");
    out.push(script.summary);
    out.push("");
    if (!script.findings.length) {
      out.push("No findings.");
      out.push("");
      continue;
    }
    out.push("| Tag | Behavior | Ref |");
    out.push("| --- | -------- | --- |");
    for (const f of script.findings) {
      const ref = f.tag === "book-specific" ? f.ref : "-";
      out.push(`| ${f.tag} | ${f.text} | ${ref} |`);
    }
    out.push("");
  }
  return out.join("\n");
}

async function generate() {
  ensureDir(DOCS_DIR);
  const inventory = buildInventory();
  await fsp.writeFile(JSON_PATH, JSON.stringify(inventory, null, 2) + "\n", "utf8");
  await fsp.writeFile(MD_PATH, buildMarkdown(inventory), "utf8");
  console.log(`Wrote ${JSON_PATH}`);
  console.log(`Wrote ${MD_PATH}`);
}

async function check() {
  const failures = [];
  if (!fs.existsSync(JSON_PATH)) failures.push(`Missing ${JSON_PATH}`);
  if (!fs.existsSync(MD_PATH)) failures.push(`Missing ${MD_PATH}`);

  let inventory = null;
  if (fs.existsSync(JSON_PATH)) {
    try {
      inventory = JSON.parse(await fsp.readFile(JSON_PATH, "utf8"));
    } catch (err) {
      failures.push(`Invalid JSON in ${JSON_PATH}: ${err.message}`);
    }
  }

  if (inventory) {
    const paths = new Set((inventory.scripts || []).map((s) => s.path));
    for (const expected of TARGET) {
      if (!paths.has(expected)) {
        failures.push(`JSON missing script ${expected}`);
      }
    }
    for (const script of inventory.scripts || []) {
      for (const f of script.findings || []) {
        if (f.tag === "book-specific") {
          if (!f.ref || !/\d+/.test(String(f.ref))) {
            failures.push(
              `Book-specific finding in ${script.path} lacks file:line ref: ${JSON.stringify(f)}`
            );
          }
        }
      }
    }
  }

  if (fs.existsSync(MD_PATH)) {
    const md = await fsp.readFile(MD_PATH, "utf8");
    if (!md.startsWith("# Exodus Factory Inventory")) {
      failures.push(`Markdown header missing in ${MD_PATH}`);
    }
    for (const expected of TARGET) {
      if (!md.includes(expected)) {
        failures.push(`Markdown missing script ${expected}`);
      }
    }
  }

  if (failures.length) {
    for (const f of failures) console.error(`✗ ${f}`);
    process.exit(1);
  }
  console.log(
    "✓ Inventory files exist, parse, cover all 8 scripts, and every book-specific finding has a file:line reference."
  );
}

if (process.argv.includes("--check")) {
  await check();
} else {
  await generate();
}
